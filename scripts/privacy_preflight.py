must("elapsedRealtime" in service and "activeSessionMs" in service,"Session timing must use monotonic active time")
must("openBatteryOptimizationSettings" in module,"User-facing battery settings access required")
must("android.permission.BIND_ACCESSIBILITY_SERVICE" in manifest,"Accessibility must use system-protected binding permission")
must("Accessibility" in (root/"components/FocusControl.js").read_text(),"Consent UI must explain Accessibility")
must("workflow_dispatch:" in workflow and "\n  push:" not in workflow,"APK workflow must stay manual-only")
must("if: ${{ inputs.publish_private_apk }}" in workflow,"Owner APK artifact must be gated by explicit publish input")
signing=(root/"scripts/ensure_qa_signing.py").read_text()
must("Stable signing secrets missing" in signing and "JOY_QA_KEYSTORE_BASE64" in signing,"Private APK must fail closed without reusable signing secrets")
must(app_cfg["expo"]["android"]["package"]=="com.joyvimo.app","QA package ID unexpectedly changed")
must("OfflineActivities" in app and "computeProgress" in app,"Offline activity and local progress flows required")
must("JoyCompanion" in app and "PrivacyDataPanel" in app and "DailyReminders" in app,"New user-facing features must be wired into App.js")
must("expo-notifications" in package["dependencies"],"Local reminder dependency missing")
