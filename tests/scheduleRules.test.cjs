const assert=require('node:assert/strict');
const {asMinute,scheduleActive}=require('../lib/scheduleRules');
assert.equal(asMinute('00:00'),0);
assert.equal(asMinute('23:59'),1439);
assert.equal(asMinute('24:00'),null);
assert.equal(asMinute('7:00'),null);
let study={enabled:true,start:'16:00',end:'18:00',days:[1,2,3,4,5]};
assert.equal(scheduleActive(study,1,960),true);
assert.equal(scheduleActive(study,1,1079),true);
assert.equal(scheduleActive(study,1,1080),false);
assert.equal(scheduleActive(study,0,960),false);
let sleep={enabled:true,start:'22:00',end:'07:00',days:[1]};
assert.equal(scheduleActive(sleep,1,1320),true);
assert.equal(scheduleActive(sleep,2,60),true);
assert.equal(scheduleActive(sleep,2,420),false);
assert.equal(scheduleActive(sleep,1,60),false);
assert.equal(scheduleActive({...sleep,enabled:false},1,1380),false);
assert.equal(scheduleActive({...sleep,start:'22:00',end:'22:00'},1,1380),false);
console.log('PASS: schedule weekday, boundaries, overnight assertions');