const assert=require('node:assert/strict');
const {todayKey,createInitial,claimAction,canJoinPublicRanking,openingAllowed}=require('../lib/policy');
const s=createInitial();
assert.equal(s.age,null);
assert.equal(s.leaderboard,false);
assert.equal(s.rules.TikTok.enabled,false);
assert.equal(canJoinPublicRanking('kid'),false);
assert.equal(canJoinPublicRanking('teen'),false);
assert.equal(canJoinPublicRanking('adult'),true);
const dt=new Date('2026-10-12T14:00:00');
const a=claimAction(s,'offline',20,dt);
assert.equal(a.awarded,true);
assert.equal(a.state.xp,20);
const b=claimAction(a.state,'offline',20,dt);
assert.equal(b.awarded,false);
assert.equal(b.state.xp,20);
assert.equal(openingAllowed({...s.rules.TikTok,enabled:true},2),true);
assert.equal(openingAllowed({...s.rules.TikTok,enabled:true},3),false);
assert.equal(openingAllowed(s.rules.TikTok,0),false);
console.log('13 policy assertions passed');