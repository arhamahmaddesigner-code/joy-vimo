const assert=require('node:assert/strict');
const {mayUseAdultLeaderboard,normalizeLoginEmail,normalizeEmailOtp,secondsUntilOtpResend,normalizeCountryCode,otpCodeBelongsToEmail,requiresOfflineAuthIsolation,canPostLeaderboardAction}=require('../lib/leaderboardAuth');
assert.equal(mayUseAdultLeaderboard('adult'),true);
assert.equal(mayUseAdultLeaderboard('teen'),false);
assert.equal(mayUseAdultLeaderboard('kid'),false);
assert.equal(normalizeLoginEmail(' TEST@Example.com '),'test@example.com');
assert.equal(normalizeLoginEmail('invalid'),null);
assert.equal(normalizeEmailOtp('123456'),'123456');
assert.equal(normalizeEmailOtp('12345'),null);
assert.equal(normalizeEmailOtp('a23456'),null);
assert.equal(normalizeCountryCode(' pk '),'PK');
assert.equal(normalizeCountryCode('P1'),null);
assert.equal(secondsUntilOtpResend(1000,30000),31);
assert.equal(secondsUntilOtpResend(1000,62000),0);
assert.equal(otpCodeBelongsToEmail(' TEST@example.com ','test@example.com'),true);
assert.equal(otpCodeBelongsToEmail('other@example.com','test@example.com'),false);
assert.equal(otpCodeBelongsToEmail('invalid','test@example.com'),false);
assert.equal(requiresOfflineAuthIsolation('kid'),true);
assert.equal(requiresOfflineAuthIsolation('teen'),true);
assert.equal(requiresOfflineAuthIsolation('adult'),false);
assert.equal(canPostLeaderboardAction('joy-calm-five'),true);
assert.equal(canPostLeaderboardAction('memory-garden'),false);
assert.equal(canPostLeaderboardAction('unknown'),false);
const app=require('node:fs').readFileSync('App.js','utf8');
assert.match(app,/ready&&requiresOfflineAuthIsolation\(data.age\)/);
assert.match(app,/canPostLeaderboardAction\(id\)/);
console.log('PASS: adult leaderboard email, OTP, resend and country checks');
